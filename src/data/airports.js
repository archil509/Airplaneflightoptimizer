/**
 * Builds a fresh AirportGraph instance for 'visualizer', 'global', or 'academic' preset.
 */
export function createDefaultGraph(dataset = 'visualizer') {
  const graph = new AirportGraph();

  if (dataset === 'visualizer') {
    for (const airport of VISUALIZER_AIRPORTS) {
      graph.addAirport(airport);
    }
    for (const route of VISUALIZER_ROUTES) {
      graph.addRoute(route, true);
    }
    return graph;
  }

  if (dataset === 'academic') {
    for (const airport of ACADEMIC_SAMPLE_AIRPORTS) {
      graph.addAirport(airport);
    }
    for (const route of ACADEMIC_SAMPLE_ROUTES) {
      graph.addRoute(route, true);
    }
    return graph;
  }

  for (const airport of GLOBAL_AIRPORTS) {
    graph.addAirport(airport);
  }
  for (const [from, to, frequencyPerDay, delayMin] of GLOBAL_ROUTE_PAIRS) {
    graph.addRoute({ from, to, frequencyPerDay, delayMin }, true);
  }
  return graph;
}
